"""Security headers on every response from the main app.

X-Frame-Options is SAMEORIGIN, not DENY: the owner's website preview is an iframe on this same
origin. Other sites still cannot frame the app. No Content-Security-Policy is set yet, because
the server-rendered pages use inline scripts and styles that a strict policy would block."""


class SecurityHeaders:
    HEADERS = (
        (b"x-content-type-options", b"nosniff"),
        (b"x-frame-options", b"SAMEORIGIN"),
        (b"referrer-policy", b"strict-origin-when-cross-origin"),
    )

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)

        async def send_with_headers(message):
            if message["type"] == "http.response.start":
                headers = list(message.get("headers", []))
                present = {name.lower() for name, _ in headers}
                for name, value in self.HEADERS:
                    if name not in present:
                        headers.append((name, value))
                message = {**message, "headers": headers}
            await send(message)

        await self.app(scope, receive, send_with_headers)
